/** Get all specialized repositories */
export const SPECIALIZED_REPOSITORIES: SpecializedRepository[] = [
  HEALTH_BEYOND_NEET,
  FINTECH_COMMERCE,
  FUTURE_READY_GREEN,
  ENGINEERING_IT,
  ARTS_HUMANITIES,
];

/** Get total stats across all specialized repos */
export function getSpecializedStats() {
  return SPECIALIZED_REPOSITORIES.map((repo) => {
    const totalClusters = repo.clusters.length;
    const totalPathways = repo.clusters.reduce((sum, c) => sum + c.pathways.length, 0);
    return { title: repo.title, icon: repo.icon, totalClusters, totalPathways };
  });
}
